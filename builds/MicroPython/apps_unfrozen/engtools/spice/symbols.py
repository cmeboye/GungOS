_cache = {}


def segments(kind, size, ux, uy):
    """Segments as offsets from the symbol's centre, turned so that pin A
    to pin B runs along (ux, uy) for two-pin symbols."""
    key = (kind, size, ux, uy)
    if key not in _cache:
        h = size // 2
        table = TWO[size] if kind in TWO[size] else UPRIGHT[size]
        out = []
        for x0, y0, x1, y1 in table[kind]:
            a, b = turn(x0 - h, y0 - h, ux, uy), turn(x1 - h, y1 - h, ux, uy)
            out.append((a[0], a[1], b[0], b[1]))
        _cache[key] = tuple(out)
    return _cache[key]


def turn(u, v, ux, uy):
    """(u along the axis, v across it) to screen offsets."""
    return u * ux - v * uy, u * uy + v * ux


def two_pin(kind):
    return kind in TWO[7]
