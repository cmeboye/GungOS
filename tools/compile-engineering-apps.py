#!/usr/bin/env python3
"""Compile and package the entry apps together with their shared SD package."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import zipfile

def replace_file(source, target):
    """Keep live simulator readers on a complete file during package refresh."""
    with tempfile.NamedTemporaryFile(dir=target.parent, prefix='.'+target.name+'.', delete=False) as handle:
        temporary=Path(handle.name)
        try:
            handle.write(source.read_bytes())
            handle.flush()
            os.replace(temporary,target)
        finally:
            temporary.unlink(missing_ok=True)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mpy-cross', default=os.environ.get('MPY_CROSS', 'mpy-cross'))
    parser.add_argument('--snapshot',type=Path,help='Override the development SD app snapshot destination.')
    parser.add_argument('--include-local-audio',action='store_true',help='Include locally supplied audio only when you have redistribution rights.')
    args = parser.parse_args()
    compiler = shutil.which(args.mpy_cross)
    if compiler is None:
        parser.error('Provide a firmware-compatible compiler with --mpy-cross PATH')
    root = Path(__file__).resolve().parents[1]
    source = root / 'builds/MicroPython/apps_unfrozen'
    files = [source / name for name in ('Graph.py', 'Graph3D.py', 'PicoLAB.py', 'Eggcel.py','Apps.py','PicoWord.py','PicoPaint.py','PicoDESK.py')]
    files += [source / name for name in ('misc/screensavers/Calculator Widget.py','misc/screensavers/Lorenz.py','games/Tetris.py')]
    files += [path for path in sorted((source / 'engtools').rglob('*.py')) if 'tools' not in path.relative_to(source).parts]
    files += sorted((source / 'desktopapps').rglob('*.py'))
    output = root / 'builds/MicroPython/apps'
    snapshot = args.snapshot or root / 'SD contents/picoware/apps'
    bundle = root / 'builds/MicroPython/engineering-preview.zip'
    sound_names=('music','menu','move','rotate','clear','tetris','level','game_over','line_fall','lock')
    assets=[]
    if args.include_local_audio:
        assets=[source/'games/tetris_sounds'/(name+'.wav') for name in sound_names]
        if any(not path.is_file() for path in assets):parser.error('Convert your own licensed audio before using --include-local-audio.')
        manifest=source/'games/tetris_sounds/manifest.json'
        if manifest.is_file():assets.append(manifest)
    # Finish all compilation before refreshing the app/package destinations.
    with tempfile.TemporaryDirectory(prefix='picoware-engineering-') as directory:
        staging = Path(directory)
        compiled = []
        for path in files:
            relative = path.relative_to(source)
            target = staging / relative.with_suffix('.mpy')
            target.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run([compiler, '-s', str(relative), '-o', str(target), str(path)], check=True)
            compiled.append(target.relative_to(staging))
        for path in assets:
            target=staging/path.relative_to(source)
            target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(path,target)
        deployed=compiled+[path.relative_to(source) for path in assets]
        for destination in (output, snapshot):
            # Retire only generated bytecode from Eggcel's former package.
            retired=destination/'engtools/eggcel'
            for name in ('__init__','app','model','formulas','charts'):
                (retired/(name+'.mpy')).unlink(missing_ok=True)
            if retired.exists() and not any(retired.iterdir()):retired.rmdir()
            for name in ('Calculator Widget','Lorenz'):
                (destination/'screensavers'/(name+'.mpy')).unlink(missing_ok=True)
            legacy_screens=destination/'screensavers'
            if legacy_screens.exists() and not any(legacy_screens.iterdir()):legacy_screens.rmdir()
            # Retire the previous name only after every new module compiles.
            old_entry = destination / 'EngineeringLab.mpy'
            if old_entry.exists():
                old_entry.unlink()
            for relative in deployed:
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                replace_file(staging / relative, target)
        with zipfile.ZipFile(bundle, 'w', zipfile.ZIP_DEFLATED) as archive:
            for relative in deployed:
                archive.write(staging / relative, 'picoware/apps/' + relative.as_posix())
            archive.writestr('INSTALL.txt',
                             'Copy/merge the picoware folder onto the root of your SD card.\n'
                             'Graph, Graph3D and PicoLAB require the complete engtools folder.\n'
                             'GungOS v2.2: Apps > PicoDESK > Eggcel/PicoWord/PicoPaint. Requires the updated UF2.\n'
                             'Desktop apps live in desktopapps, separate from engineering engtools.\n'
                             'Eggcel workbooks are saved explicitly under picoware/documents/eggcel.\n'
                             'Keep one .py or .mpy copy of each module in the deployed app tree.\n'
                             'Exit the app before replacing files, then relaunch it.\n'
                             'The new hierarchy/shared theme requires the updated UF2; later app edits can use SD updates.\n'
                             'PicoLAB includes Calculate, Statistics, Solver, Complex, Base-N and Matrix.\n'
                             'This bundle includes Tetris, Lorenz and a native-size Calculator Widget.\n'
                             'Audio is optional and excluded by default; see guides/TetrisAudio.md for your own licensed assets.\n'
                             'Calculator integrals require native ulab; basic arithmetic does not.\n'
                             'Calculator Statistics requires the configured native ulab build with numpy.sort.\n'
                             'Numerics checks requires the custom firmware containing the selected ulab build.\n'
                             'The native ulab library cannot be installed by copying SD files.\n')
            archive.writestr('LICENSE.txt',(root/'LICENSE').read_text())
            archive.writestr('CREDITS.txt',
                             'GungOS by Cem Gungor.\n'
                             'Based on the open-source Picoware project by jblanked.\n'
                             'Picoware-derived distribution: GNU GPL version 3.\n'
                             'The previous Tetris game was based on lazerduck/PicoCalc_Dashboard.\n'
                             'The complete firmware also includes MicroPython, ulab and other components\n'
                             'under their respective licenses; see the source distribution.\n')
        desktop_bundle=bundle.with_name('DesktopApps-preview.zip')
        with zipfile.ZipFile(desktop_bundle,'w',zipfile.ZIP_DEFLATED) as archive:
            for relative in compiled:
                if relative.parts[0]=='games' or relative.as_posix()=='misc/screensavers/Lorenz.mpy':continue
                archive.write(staging/relative,'picoware/apps/'+relative.as_posix())
            archive.writestr('INSTALL.txt',
                             'Merge picoware into the SD root, replacing the matching app modules.\n'
                             'GungOS v2.2: Apps > PicoDESK > Eggcel / PicoWord / PicoPaint.\n'
                             'Keep desktopapps and engtools complete. Requires the updated firmware UF2.\n'
                             'Keep only one .py or .mpy copy per module.\n'
                             'Your existing documents and settings are not included or replaced.\n'
                             'Read DesktopApps.md and Eggcel.md for keys, formats and current limits.\n')
            for name in ('DesktopApps','Eggcel'):
                archive.write(root/'guides'/(name+'.md'),name+'.md')
            archive.write(root/'LICENSE','LICENSE.txt')
        # The previous Eggcel download now includes its relocated package and launcher.
        replace_file(desktop_bundle,bundle.with_name('Eggcel-preview.zip'))
    print('Compiled {} modules; refreshed builds and the workspace SD snapshot.'.format(len(compiled)))
    print('Install bundle:', bundle)
    print('Desktop apps bundle:', desktop_bundle)


if __name__ == '__main__':
    main()
