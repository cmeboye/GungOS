#!/usr/bin/env python3
"""Convert pinned Spleen BDF glyphs to GungOS's existing ASCII font slots."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/fonts/spleen'
# Preserve the existing width, height and spacing contracts used by app layouts.
SLOTS = ((5, 8, 1, '5x8'), (7, 12, 1, '6x12'),
         (11, 16, 1, '8x16'), (14, 20, 0, '8x16'),
         (17, 24, 0, '12x24'))


def read_bdf(path):
    glyphs = {}
    bitmap = None
    for line in path.read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'FONTBOUNDINGBOX':
            bounds = tuple(map(int, fields[1:]))
        elif fields[0] == 'STARTCHAR':
            bitmap = None
        elif fields[0] == 'ENCODING':
            code = int(fields[1])
        elif fields[0] == 'BBX':
            box = tuple(map(int, fields[1:]))
        elif fields[0] == 'BITMAP':
            bitmap = []
        elif fields[0] == 'ENDCHAR':
            glyphs[code] = (box, bitmap)
            bitmap = None
        elif bitmap is not None:
            bitmap.append(bytes.fromhex(line.strip()))
    return bounds, glyphs


def convert(width, height, spacing, face):
    bounds, glyphs = read_bdf(SOURCE / ('spleen-' + face + '.bdf'))
    bw, bh, bx, by = bounds
    assert bw <= width and bh <= height
    pad_x, pad_y = (width - bw) // 2, (height - bh) // 2
    stride = (width + 7) // 8
    license_text = (SOURCE / 'LICENSE').read_text().strip()
    lines = ['/*', *((' * ' + line).rstrip() for line in license_text.splitlines()),
             ' *', ' * Generated by tools/convert-spleen-fonts.py; do not edit.',
             ' * Spleen %s centered in the legacy %dx%d cell.' % (face, width, height),
             ' */', '#include "font.h"', '',
             'static const uint8_t Font%d_Table[] = {' % height]
    for code in range(32, 127):
        (gw, gh, gx, gy), rows = glyphs[code]
        assert len(rows) == gh
        cell = bytearray(stride * height)
        for y, row in enumerate(rows):
            for x in range(gw):
                if row[x // 8] & (0x80 >> (x % 8)):
                    dx = pad_x + gx - bx + x
                    dy = pad_y + by + bh - gy - gh + y
                    assert 0 <= dx < width and 0 <= dy < height
                    cell[dy * stride + dx // 8] |= 0x80 >> (dx % 8)
        lines.append('    // ASCII %d' % code)
        for row in range(height):
            lines.append('    ' + ', '.join('0x%02X' % value for value in
                         cell[row * stride:(row + 1) * stride]) + ',')
    lines += ['};', '', 'const FontTable Font%d = {' % height,
              '    Font%d_Table, %d, %d, %d' % (height, width, height, spacing),
              '};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for slot in SLOTS:
        path = ROOT / ('src/MicroPython/font/font%d.c' % slot[1])
        content = convert(*slot)
        if args.check:
            if path.read_text() != content:
                raise SystemExit('Font needs regeneration: ' + str(path))
        else:
            path.write_text(content)
    print('Spleen: all five ASCII font tables ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
