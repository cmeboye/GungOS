#!/usr/bin/env python3
"""Compile the supplied status PNGs into indexed RGBA firmware assets."""
import argparse
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'wifi_connected': 'wifi/wifi_connected.png',
    'wifi_disconnected': 'wifi/wifi_notconnected.png',
    'bluetooth_connected': 'bluetooth/bluetooth_connected.png',
    'bluetooth_disconnected': 'bluetooth/bluetooth_notconnected.png',
}


def compile_icons(assets):
    palette = [(0, 0, 0, 0)]
    indices = {palette[0]: 0}
    icons = []
    for name, filename in SOURCES.items():
        with Image.open(assets / filename) as original:
            im = original.convert('RGBA')
        expected = (12, 12)
        if im.size != expected:
            raise ValueError(filename + ': expected ' + str(expected) + ', got ' + str(im.size))
        pixels = bytearray()
        rgba_bytes = im.tobytes()
        for offset in range(0, len(rgba_bytes), 4):
            pixel = tuple(rgba_bytes[offset:offset + 4])
            rgba = pixel if pixel[3] else palette[0]
            if rgba not in indices:
                if len(palette) == 256:
                    raise ValueError('Status artwork exceeds the shared 256-colour palette')
                indices[rgba] = len(palette)
                palette.append(rgba)
            pixels.append(indices[rgba])
        icons.append((name, im.width, im.height, bytes(pixels)))
    text = ['"""Generated by tools/compile-status-icons.py; edit the source PNGs."""', '', 'PALETTE = (']
    text.extend('    ' + repr(rgba) + ',' for rgba in palette)
    text += [')', '', 'ICONS = {']
    for name, width, height, pixels in icons:
        text.append('    ' + repr(name) + ': (' + str(width) + ', ' + str(height) + ', (')
        text.extend('        ' + repr(pixels[offset:offset + 48]) for offset in range(0, len(pixels), 48))
        text.append('    )),')
    text += ['}', '']
    return '\n'.join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the generated module is stale.')
    args = parser.parse_args()
    output = ROOT / 'src/MicroPython/picoware/assets/status_icons.py'
    content = compile_icons(ROOT / 'assets/status-bar')
    if args.check:
        if not output.exists() or output.read_text() != content:
            parser.exit(1, 'Status icon module is stale; run tools/compile-status-icons.py\n')
        print('PASS: compiled status assets match all %d PNGs' % len(SOURCES))
    else:
        output.write_text(content)
        print('Compiled %d status icons: %s' % (len(SOURCES), output))


if __name__ == '__main__':
    main()
