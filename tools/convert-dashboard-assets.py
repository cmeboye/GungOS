#!/usr/bin/env python3
"""Pack assets/logos PNGs for the desktop and theme-aware menu headers."""
import argparse
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('gungOS_large', 'gungOS_small', 'picodesk', 'picolab')


def compile_logos():
    output = ['"""Generated from assets/logos; transparent canvas with theme text and accent colours."""',
              'LOGOS = {']
    sizes = {}
    for name in NAMES:
        with Image.open(ROOT / 'assets/logos' / (name + '.png')) as source:
            image = source.convert('RGBA')
        width, height = image.size
        if width > (139 if name == 'gungOS_large' else 90) or height > 25:
            raise ValueError(name + ' exceeds the native header area')
        sizes[name] = (width, height)
        # Slots 0/1 are the destination background and optional theme accent.
        palette, lookup, runs = [0, None], {}, bytearray()
        for position, (r, g, b, alpha) in enumerate(image.getdata()):
            if alpha not in (0, 255):
                raise ValueError(name + ': use fully transparent or opaque pixels')
            if not alpha:
                index = 0
            elif name in ('gungOS_large', 'gungOS_small') and max(r, g, b) < 90:
                # Black lettering is stored as white, which decode() swaps for the text colour.
                if 0xFFFF not in lookup:
                    lookup[0xFFFF] = len(palette)
                    palette.append(0xFFFF)
                index = lookup[0xFFFF]
            elif name == 'gungOS_large' and r > 150 and g < 100 and b < 100 and position % width > 26:
                index = 1  # red outside the cube icon follows the accent
            elif name in ('gungOS_small', 'picodesk', 'picolab') and r > 150 and g < 100 and b < 100:
                index = 1
            else:
                color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                if color not in lookup:
                    if len(palette) >= 256:
                        raise ValueError(name + ' exceeds the indexed colour limit')
                    lookup[color] = len(palette)
                    palette.append(color)
                index = lookup[color]
            if runs and runs[-1] == index and runs[-2] < 255:
                runs[-2] += 1
            else:
                runs.extend((1, index))
        output.append('    %r: (%d, %d, %r, (' % (name, width, height, tuple(palette)))
        output.extend('        ' + repr(bytes(runs[i:i+72])) for i in range(0, len(runs), 72))
        output.append('    )),')
    output.extend(['}', '''
def decode(name, background=0, accent=0xF800, ink=None):
    width, height, palette, runs = LOGOS[name]
    out = bytearray(width * height * 2)
    from picoware.gui.appearance import text_on
    if ink is None: ink = text_on(background)
    position = 0
    for i in range(0, len(runs), 2):
        count, index = runs[i], runs[i+1]
        color = background if index == 0 else accent if index == 1 else palette[index]
        if color == 0xFFFF and index > 1:
            color = ink
        run = bytes((color & 255, color >> 8)) * count
        out[position:position+len(run)] = run
        position += len(run)
    return out


_decoded = {}  # (name, background, accent, ink) -> pixels; a header repaints each draw


def paint(draw, name, x, y, background=0, accent=0xF800, ink=None):
    width, height = LOGOS[name][:2]
    key = (name, background, accent, ink)
    pixels = _decoded.get(key)
    if pixels is None:
        if len(_decoded) >= 4:  # colours change only with the theme
            _decoded.clear()
        pixels = _decoded[key] = decode(name, background, accent, ink)
    draw._bytearray(x, y, width, height, pixels)
    return width
'''])
    width, height = sizes['gungOS_large']
    x, y = (139-width)//2, 20
    if y + height > 42:
        y = 42-height
    dashboard = '\n'.join([
        '"""Native desktop logo; generated by tools/convert-dashboard-assets.py."""',
        'X, Y, WIDTH, HEIGHT = %d, %d, %d, %d' % (x, y, width, height),
        '', 'def decode(dark=True, background=0, accent=0xF800, ink=None):',
        '    from picoware.assets.logos import decode as unpack',
        "    return unpack('gungOS_large', background, accent, ink)", ''])
    return '\n'.join(output), dashboard


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check packed logos match source PNGs.')
    args = parser.parse_args()
    logos, dashboard = compile_logos()
    for name, content in (('logos.py', logos), ('dashboard_logo.py', dashboard)):
        path = ROOT / 'src/MicroPython/picoware/assets' / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, 'Packed logos are stale; run tools/convert-dashboard-assets.py\n')
        else:
            path.write_text(content)
    print('PASS: packed logos match source PNGs' if args.check else 'Packed four native-resolution logos')


if __name__ == '__main__':
    main()
